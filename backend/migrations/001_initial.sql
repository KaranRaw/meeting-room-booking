CREATE EXTENSION IF NOT EXISTS btree_gist;

CREATE TABLE IF NOT EXISTS rooms (
    id INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    name VARCHAR(80) NOT NULL UNIQUE,
    capacity INTEGER NOT NULL CHECK (capacity > 0),
    equipment VARCHAR(160) NOT NULL
);

CREATE TABLE IF NOT EXISTS bookings (
    id INTEGER GENERATED ALWAYS AS IDENTITY PRIMARY KEY,
    room_id INTEGER NOT NULL REFERENCES rooms(id),
    title VARCHAR(120) NOT NULL CHECK (length(trim(title)) > 0),
    booking_date DATE NOT NULL,
    start_time TIME WITHOUT TIME ZONE NOT NULL,
    end_time TIME WITHOUT TIME ZONE NOT NULL,
    created_at TIMESTAMPTZ NOT NULL DEFAULT now(),
    CONSTRAINT booking_working_hours CHECK (
        start_time >= TIME '09:00' AND end_time <= TIME '18:00'
        AND end_time > start_time
    ),
    CONSTRAINT booking_whole_minutes CHECK (
        extract(second FROM start_time) = 0 AND extract(second FROM end_time) = 0
    ),
    -- The exclusive end keeps adjacent meetings legal, even for direct SQL inserts.
    CONSTRAINT bookings_no_overlap EXCLUDE USING gist (
        room_id WITH =,
        tsrange(booking_date + start_time, booking_date + end_time, '[)') WITH &&
    )
);

CREATE INDEX IF NOT EXISTS bookings_date_idx ON bookings (booking_date);
CREATE INDEX IF NOT EXISTS bookings_room_date_start_idx
    ON bookings (room_id, booking_date, start_time);

